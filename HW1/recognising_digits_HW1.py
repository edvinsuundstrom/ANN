def sgn(value):
    return 1 if value >= 0 else -1

# Initialize weights according to Hebb's rule
def init_weights(X):
    N = X.shape[0]
    weight_matrix = (1 / N) * np.matmul(X, X.T)
    np.fill_diagonal(weight_matrix, 0)
    return weight_matrix

# McCulloch-Pitts dynamics
def mcculloch_pitts_update(weights, states):
    N = len(states)
    for j in range(N):
        bm = np.dot(weights[j, :], states)
        states[j] = sgn(bm)
    return states

